#!/usr/bin/env bash
# Start the LOCAL production-like stack (BRAIN/docs/PRODLIKE.md) and leave it running. Idempotent: re-run any time.
#   scripts/prodlike/up.sh                  build the prod image from the committed HEAD (git archive = what CI builds)
#   scripts/prodlike/up.sh --worktree       build from the working tree instead (test an uncommitted fix)
#   scripts/prodlike/up.sh --image REF      run a published image instead, e.g. ghcr.io/martinsdonins/majas-paligs:main
#                                           (docker login ghcr.io first — the package is private)
#   scripts/prodlike/up.sh --no-build       reuse the existing majas-paligs:prodlike image
# Then: seeds structure data (db:seed --force, like production) and makes admin@example.test a platform admin,
# saving its TOTP secret to storage/app/prodlike/admin-totp.txt (git-ignored).
set -euo pipefail
export MSYS_NO_PATHCONV=1
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
state="$root/storage/app/prodlike"
env_file="$state/prodlike.env"
admin_email="${PRODLIKE_ADMIN_EMAIL:-admin@example.test}"
image="majas-paligs:prodlike"
mode="head"

while [ $# -gt 0 ]; do
  case "$1" in
    --worktree) mode="worktree" ;;
    --no-build) mode="none" ;;
    --image) mode="pull"; image="${2:?--image needs a reference}"; shift ;;
    *) echo "Unknown option: $1" >&2; exit 2 ;;
  esac
  shift
done

mkdir -p "$state/screens"
dc() { "$here/dc.sh" "$@"; }

rand_hex() { openssl rand -hex "$1" 2>/dev/null || head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }
rand_key() { echo "base64:$(openssl rand -base64 32 2>/dev/null || head -c 32 /dev/urandom | base64)"; }

# 1. Secrets — generated ONCE (stable APP_KEY = sessions and encrypted columns survive re-runs).
if [ ! -s "$env_file" ]; then
  umask 077
  cat > "$env_file" <<ENV
# Generated by scripts/prodlike/up.sh — LOCAL prodlike secrets only. Never reuse in production.
COMPOSE_PROJECT_NAME=majas-prodlike
APP_URL=https://localhost:8443
MAJAS_PUBLIC_HOST=localhost:8443
APP_KEY=$(rand_key)
APP_PREVIOUS_KEYS=
INVITE_KEY=$(rand_key)
PLATE_ENC_KEY=$(rand_key)
PLATE_INDEX_KEY=$(rand_key)
PLATE_ENC_KEY_PREVIOUS=
PG_SUPERUSER_PASSWORD=$(rand_hex 16)
DB_HOST=pgsql
DB_PORT=5432
DB_DATABASE=majas
DB_SSLMODE=require
DB_OWNER_PASSWORD=$(rand_hex 16)
DB_PASSWORD=$(rand_hex 16)
DB_RETENTION_PASSWORD=$(rand_hex 16)
REDIS_HOST=redis
REDIS_PASSWORD=$(rand_hex 16)
MAIL_MAILER=smtp
MAIL_HOST=mailpit
MAIL_PORT=1025
MAIL_USERNAME=
MAIL_PASSWORD=
MAIL_FROM_ADDRESS=noreply@kaimini.test
SENTRY_LARAVEL_DSN=
PLATFORM_ALERT_EMAIL=alerts@example.test
ENV
  echo "Secrets written to storage/app/prodlike/prodlike.env"
fi

# 2. Image.
case "$mode" in
  head)
    rev="$(git -C "$root" rev-parse HEAD)"
    echo "Building $image (prod target) from HEAD ${rev:0:12}…"
    git -C "$root" archive --format=tar HEAD \
      | docker build --target prod -t "$image" --label "org.opencontainers.image.revision=$rev" -
    ;;
  worktree)
    echo "Building $image (prod target) from the WORKING TREE…"
    docker build --target prod -t "$image" --label "org.opencontainers.image.revision=worktree" "$(cd "$root" && (pwd -W 2>/dev/null || pwd))"
    ;;
  pull) docker pull "$image" ;;
  none) docker image inspect "$image" >/dev/null ;;
esac
# MAJAS_IMAGE is read by docker/compose.prod.yaml (and the cert helper).
if grep -q '^MAJAS_IMAGE=' "$env_file"; then
  sed -i "s#^MAJAS_IMAGE=.*#MAJAS_IMAGE=$image#" "$env_file"
else
  echo "MAJAS_IMAGE=$image" >> "$env_file"
fi

# 3. Up (migrate runs again on every up — same as every Coolify deploy).
dc up -d --remove-orphans

echo -n "Waiting for web to become healthy"
for _ in $(seq 1 90); do
  status="$(docker inspect -f '{{.State.Health.Status}}' "$(dc ps -q web)" 2>/dev/null || echo starting)"
  [ "$status" = "healthy" ] && break
  if [ -n "$(dc ps -a -q migrate)" ] && [ "$(docker inspect -f '{{.State.Status}} {{.State.ExitCode}}' "$(dc ps -a -q migrate)")" = "exited 1" ]; then
    echo; echo "migrate FAILED:" >&2; dc logs --no-log-prefix migrate | tail -40 >&2; exit 1
  fi
  echo -n "."; sleep 2
done
echo " $status"
[ "$status" = "healthy" ] || { dc ps -a; dc logs --tail 60 web >&2; exit 1; }

code="$(curl -sk -o /dev/null -w '%{http_code}' https://localhost:8443/up || true)"
echo "https://localhost:8443/up → $code"
[ "$code" = "200" ] || { echo "Proxy not answering 200 on /up" >&2; dc logs --tail 40 proxy >&2; exit 1; }

# 4. Structure seed exactly like production (web container, majas_app connection). Idempotent seeders.
dc exec -T web php artisan db:seed --force --no-interaction

# 5. Platform admin. An existing TOTP secret is always kept; without a saved copy, ask for a new one (--reset-totp).
totp_file="$state/admin-totp.txt"
args=()
[ -s "$totp_file" ] || args=(--reset-totp)
out="$(dc exec -T web php artisan majas:platform-admin "$admin_email" "${args[@]}" --no-interaction | tr -d '\r')"
secret="$(printf '%s\n' "$out" | grep -E '^([A-Z2-7]{4} ?)+$' | head -1 | tr -d ' \r' || true)"
if [ -n "$secret" ]; then
  printf '%s\n' "$secret" > "$totp_file"
  printf '%s\n' "$out" | grep '^otpauth://' | tr -d '\r' > "$state/admin-totp.uri" || true
  echo "New TOTP secret for $admin_email saved to storage/app/prodlike/admin-totp.txt"
else
  echo "Platform admin $admin_email kept its TOTP secret (storage/app/prodlike/admin-totp.txt)"
fi

# 6. Caddy's local root CA (optional: import it to trust https://localhost:8443 without a warning).
dc cp proxy:/data/caddy/pki/authorities/local/root.crt "$(cd "$state" && (pwd -W 2>/dev/null || pwd))/caddy-root.crt" >/dev/null 2>&1 || true

cat <<INFO

Prodlike stack is RUNNING (image: $image)
  App        https://localhost:8443          (self-signed: accept the warning or import storage/app/prodlike/caddy-root.crt)
  Platform   https://localhost:8443/admin/platform (admin: $admin_email — code via mail, then TOTP)
  Mailpit    http://127.0.0.1:8036
  Mail code  scripts/prodlike/mail-code.sh $admin_email
  TOTP code  scripts/prodlike/totp.sh
  Logs       scripts/prodlike/dc.sh logs -f web worker
  Smoke      scripts/prodlike/browser.sh
  Stop       scripts/prodlike/down.sh   (--wipe = also delete data)
INFO
